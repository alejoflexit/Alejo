-- Devoluciones (cancelados y cambios) + remitos con QR. Se puede correr más de una vez.
create table if not exists public.devoluciones (
  did bigint primary key,
  tipo text not null check (tipo in ('CANCELADO','CAMBIO')),
  cliente text, ml_venta_id text, tracking text, cp text, zona text,
  estado_ld int, devuelto_ld boolean default false, fecha_dev_ld timestamptz,
  li_texto text,
  fecha_alta timestamptz, fecha_cancelado timestamptz, fecha_retiro timestamptz,
  fecha_devuelto_cliente timestamptz,
  en_deposito_ld boolean default false, fecha_deposito timestamptz,
  cadete text, valor numeric,
  detalle_at timestamptz,
  actualizado_at timestamptz default now()
);
create index if not exists devoluciones_tipo_idx on public.devoluciones (tipo, estado_ld);

create table if not exists public.devoluciones_gestion (
  did bigint primary key,
  tipo_override text check (tipo_override in ('CANCELADO','CAMBIO','NO_ES')),
  ingreso_deposito_at timestamptz, ingreso_por text,
  marca text check (marca in ('extraviado','reclamado','descartado')),
  marca_nota text, marca_por text, marca_at timestamptz,
  actualizado_at timestamptz default now()
);

create table if not exists public.remitos_devolucion (
  id bigint generated by default as identity primary key,
  codigo text unique,
  cliente text not null,
  dids bigint[] not null,
  creado_por text, creado_at timestamptz default now(),
  estado text not null default 'emitido' check (estado in ('emitido','procesando','devuelto','error','anulado')),
  foto_path text, firmado_por text, firmado_at timestamptz,
  procesado_at timestamptz, resultado jsonb, error text
);
create or replace function public.remito_codigo() returns trigger language plpgsql set search_path = public as $$
begin
  if new.codigo is null then new.codigo := 'RD-' || lpad(new.id::text, 5, '0'); end if;
  return new;
end $$;
drop trigger if exists remito_codigo_trg on public.remitos_devolucion;
create trigger remito_codigo_trg before insert on public.remitos_devolucion for each row execute function public.remito_codigo();

create table if not exists public.devoluciones_sync (
  id int primary key default 1 check (id = 1),
  ultima_at timestamptz, ok boolean, detalle text, pedido_at timestamptz
);
insert into public.devoluciones_sync (id) values (1) on conflict do nothing;

alter table public.devoluciones enable row level security;
alter table public.devoluciones_gestion enable row level security;
alter table public.remitos_devolucion enable row level security;
alter table public.devoluciones_sync enable row level security;

drop policy if exists "dev leer" on public.devoluciones;
drop policy if exists "devsync leer" on public.devoluciones_sync;
drop policy if exists "gest leer" on public.devoluciones_gestion;
drop policy if exists "gest insertar" on public.devoluciones_gestion;
drop policy if exists "gest editar" on public.devoluciones_gestion;
drop policy if exists "rem leer" on public.remitos_devolucion;
drop policy if exists "rem insertar" on public.remitos_devolucion;
drop policy if exists "rem editar" on public.remitos_devolucion;
create policy "dev leer" on public.devoluciones for select to authenticated using (true);
create policy "devsync leer" on public.devoluciones_sync for select to authenticated using (true);
create policy "gest leer" on public.devoluciones_gestion for select to authenticated using (true);
create policy "gest insertar" on public.devoluciones_gestion for insert to authenticated with check (true);
create policy "gest editar" on public.devoluciones_gestion for update to authenticated using (true) with check (true);
create policy "rem leer" on public.remitos_devolucion for select to authenticated using (true);
create policy "rem insertar" on public.remitos_devolucion for insert to authenticated with check (estado = 'emitido');
-- El equipo solo puede subir la foto firmada (→ procesando) o anular. "devuelto"/"error" lo pone el sync.
create policy "rem editar" on public.remitos_devolucion for update to authenticated
  using (estado in ('emitido','error','procesando')) with check (estado in ('emitido','procesando','anulado'));

-- Fotos de remitos firmados (privado)
insert into storage.buckets (id, name, public) values ('remitos-firmados','remitos-firmados', false) on conflict do nothing;
drop policy if exists "remitos subir" on storage.objects;
drop policy if exists "remitos ver" on storage.objects;
create policy "remitos subir" on storage.objects for insert to authenticated with check (bucket_id = 'remitos-firmados');
create policy "remitos ver" on storage.objects for select to authenticated using (bucket_id = 'remitos-firmados');
