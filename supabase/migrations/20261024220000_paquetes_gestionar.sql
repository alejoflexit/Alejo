-- Bandeja "A gestionar": paquetes que llegan al depósito y no se sabe de quién son (foto + quién lo trajo + notas)
create table if not exists public.paquetes_gestionar (
  id bigint generated by default as identity primary key,
  creado_at timestamptz not null default now(),
  creado_por text,
  cadete text,
  nota text,
  fotos text[] not null default '{}',
  estado text not null default 'pendiente' check (estado in ('pendiente','vinculado','resuelto')),
  did bigint,
  resolucion text,
  resuelto_por text,
  resuelto_at timestamptz,
  notas jsonb not null default '[]'::jsonb
);
alter table public.paquetes_gestionar enable row level security;
create policy "pg leer" on public.paquetes_gestionar for select to authenticated using (true);
create policy "pg insertar" on public.paquetes_gestionar for insert to authenticated with check (estado = 'pendiente');
create policy "pg editar" on public.paquetes_gestionar for update to authenticated using (true) with check (true);
